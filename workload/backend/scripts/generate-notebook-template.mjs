import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const backendRoot = resolve(here, "..");
const sourcePath = resolve(backendRoot, "..", "notebooks", "sync_template.py");
const targetPath = resolve(backendRoot, "src", "services", "notebook-template.ts");

const template = readFileSync(sourcePath, "utf8");
const output = `// Generated by npm run generate:notebook-template. Do not edit by hand.\nexport const ASMDB_SYNC_TEMPLATE = ${JSON.stringify(template)};\n`;

writeFileSync(targetPath, output, "utf8");
console.log(`Regenerated ${targetPath}`);
